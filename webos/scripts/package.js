'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const child = require('child_process');
require('./assets');
const root = path.resolve(__dirname, '..');
const destination = path.join(root, 'dist');
fs.mkdirSync(destination, { recursive: true });
const executable = path.join(root, 'node_modules/.bin/ares-package');
const result = child.spawnSync(executable, ['--no-minify', '--outdir', destination, path.join(root, 'app')], { stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status || 1);
const info = JSON.parse(fs.readFileSync(path.join(root, 'app/appinfo.json')));
const name = info.id + '_' + info.version + '_all.ipk';
const file = path.join(destination, name);
if (!fs.existsSync(file)) throw new Error('The expected installable package was not produced.');
const hash = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
fs.writeFileSync(file + '.sha256', hash + '  ' + name + '\n');
console.log('Validated package:', name, fs.statSync(file).size, 'bytes');
